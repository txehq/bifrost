// Operations the Deepgram provider does not serve. Bifrost reaches Deepgram for one
// operation, pre-recorded transcription (POST /v1/listen); every other operation returns
// the standard unsupported-operation error. Deepgram's text-to-speech (Aura) and its
// realtime WebSocket API are not integrated.
