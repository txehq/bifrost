// Package bfl implements the provider for Black Forest Labs' own API: FLUX images, which
// BFL serves only as tasks (submit, then poll a polling_url), and FLUX 3 video.
//
// This file registers the provider. Images are served on the image task routes
// (images.go, schemas.ImageTaskProvider); every operation of the Provider interface,
// sync images included, answers the unsupported-operation error, so a configured
// provider never calls upstream for an operation it cannot convert.
package bfl

import (
	"context"
	"strings"
	"time"

	providerUtils "github.com/capsohq/bifrost/core/providers/utils"
	schemas "github.com/capsohq/bifrost/core/schemas"
	"github.com/valyala/fasthttp"
)

// BFLProvider implements the Provider interface for Black Forest Labs' API.
type BFLProvider struct {
	logger              schemas.Logger        // Logger for provider operations
	client              *fasthttp.Client      // HTTP client for unary API requests (ReadTimeout bounds overall response)
	streamingClient     *fasthttp.Client      // HTTP client for streaming API requests (no ReadTimeout; idle governed by NewIdleTimeoutReader)
	networkConfig       schemas.NetworkConfig // Network configuration including extra headers
	sendBackRawRequest  bool                  // Whether to include raw request in BifrostResponse
	sendBackRawResponse bool                  // Whether to include raw response in BifrostResponse
}

// NewBFLProvider creates a new BFL provider instance.
//
// network_config.base_url is BFL's global endpoint by default; set it to a regional
// endpoint (https://api.eu.bfl.ai, https://api.us.bfl.ai) to keep requests in a region.
func NewBFLProvider(config *schemas.ProviderConfig, logger schemas.Logger) (*BFLProvider, error) {
	config.CheckAndSetDefaults()

	requestTimeout := time.Second * time.Duration(config.NetworkConfig.DefaultRequestTimeoutInSeconds)
	client := &fasthttp.Client{
		ReadTimeout:         requestTimeout,
		WriteTimeout:        requestTimeout,
		MaxConnsPerHost:     config.NetworkConfig.MaxConnsPerHost,
		MaxIdleConnDuration: time.Second * time.Duration(config.NetworkConfig.KeepAliveTimeoutInSeconds),
		MaxConnWaitTimeout:  requestTimeout,
		MaxConnDuration:     time.Second * time.Duration(schemas.DefaultMaxConnDurationInSeconds),
		ConnPoolStrategy:    fasthttp.FIFO,
	}

	client = providerUtils.ConfigureProxy(client, config.ProxyConfig, logger)
	client = providerUtils.ConfigureDialer(client, config.NetworkConfig.AllowPrivateNetwork)
	client = providerUtils.ConfigureTLS(client, config.NetworkConfig, logger)
	streamingClient := providerUtils.BuildStreamingClient(client)

	if config.NetworkConfig.BaseURL == "" {
		config.NetworkConfig.BaseURL = DefaultBaseURL
	}
	config.NetworkConfig.BaseURL = strings.TrimRight(config.NetworkConfig.BaseURL, "/")

	return &BFLProvider{
		logger:              logger,
		client:              client,
		streamingClient:     streamingClient,
		networkConfig:       config.NetworkConfig,
		sendBackRawRequest:  config.SendBackRawRequest,
		sendBackRawResponse: config.SendBackRawResponse,
	}, nil
}

// GetProviderKey returns the provider identifier for BFL.
func (provider *BFLProvider) GetProviderKey() schemas.ModelProvider {
	return schemas.BFL
}

// requestURL joins the configured base (global or regional) and a BFL path such as
// /v1/flux-2-pro.
func (provider *BFLProvider) requestURL(ctx *schemas.BifrostContext, path string) string {
	return provider.networkConfig.BaseURL + providerUtils.GetPathFromContext(ctx, path)
}

// setRequestHeaders writes the configured extra headers and then BFL's x-key auth header,
// so an extra header can never replace the key.
func (provider *BFLProvider) setRequestHeaders(ctx context.Context, req *fasthttp.Request, key schemas.Key) {
	providerUtils.SetExtraHeaders(ctx, req, provider.networkConfig.ExtraHeaders, nil)
	setAuthHeader(req, key)
}

// doRequest sends one request to BFL and returns the body of a 2xx answer. Any other status is
// BFL's error, with its status code kept (parseBFLError).
func (provider *BFLProvider) doRequest(ctx *schemas.BifrostContext, key schemas.Key, method, requestURL string, jsonData []byte, sendBackRawRequest, sendBackRawResponse bool) ([]byte, time.Duration, *schemas.BifrostError) {
	return provider.doRequestCaptured(ctx, key, method, requestURL, jsonData, jsonData, sendBackRawRequest, sendBackRawResponse)
}

// doRequestCaptured is doRequest with a separate captured copy of the body: jsonData goes to BFL,
// captured is what an error carries as its raw request. They differ when the body holds a
// credential from the key configuration, which the caller never sent (TXE-7062).
func (provider *BFLProvider) doRequestCaptured(ctx *schemas.BifrostContext, key schemas.Key, method, requestURL string, jsonData, captured []byte, sendBackRawRequest, sendBackRawResponse bool) ([]byte, time.Duration, *schemas.BifrostError) {
	req := fasthttp.AcquireRequest()
	resp := fasthttp.AcquireResponse()
	defer fasthttp.ReleaseRequest(req)
	defer fasthttp.ReleaseResponse(resp)

	provider.setRequestHeaders(ctx, req, key)
	req.SetRequestURI(requestURL)
	req.Header.SetMethod(method)
	if jsonData != nil {
		req.Header.SetContentType("application/json")
		req.SetBody(jsonData)
	}

	latency, bifrostErr, wait := providerUtils.MakeRequestWithContext(ctx, provider.client, req, resp)
	defer wait()
	if bifrostErr != nil {
		return nil, latency, bifrostErr
	}
	if resp.StatusCode() < fasthttp.StatusOK || resp.StatusCode() >= fasthttp.StatusMultipleChoices {
		return nil, latency, providerUtils.EnrichError(ctx, parseBFLError(resp), captured, nil, sendBackRawRequest, sendBackRawResponse, latency)
	}
	body, err := providerUtils.CheckAndDecodeBody(resp)
	if err != nil {
		rawErrBody := append([]byte(nil), resp.Body()...)
		return nil, latency, providerUtils.EnrichError(ctx, providerUtils.NewBifrostOperationError(schemas.ErrProviderResponseDecode, err), captured, rawErrBody, sendBackRawRequest, sendBackRawResponse, latency)
	}
	return append([]byte(nil), body...), latency, nil
}

