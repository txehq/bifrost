// Package googlecloudtts implements the Google Cloud Text-to-Speech provider.
//
// The provider serves one operation, text:synthesize, on the unified speech route. The
// vendor API is documented at
// https://docs.cloud.google.com/text-to-speech/docs/reference/rest/v1/text/synthesize.
package googlecloudtts

import (
	"context"
	"encoding/base64"
	"net/http"
	"strings"
	"time"

	"github.com/bytedance/sonic"
	providerUtils "github.com/capsohq/bifrost/core/providers/utils"
	schemas "github.com/capsohq/bifrost/core/schemas"
	"github.com/valyala/fasthttp"
)

const (
	// defaultBaseURL is the service endpoint of the Cloud Text-to-Speech REST API
	// ("POST https://texttospeech.googleapis.com/v1/text:synthesize").
	defaultBaseURL = "https://texttospeech.googleapis.com"
	// synthesizePath is the path of the text.synthesize method.
	synthesizePath = "/v1/text:synthesize"
	// apiKeyHeader carries a Google Cloud API key on a REST call
	// (https://docs.cloud.google.com/docs/authentication/api-keys-use).
	apiKeyHeader = "x-goog-api-key"
)

// GoogleCloudTTSProvider implements the Provider interface for Google Cloud Text-to-Speech.
type GoogleCloudTTSProvider struct {
	logger              schemas.Logger        // Logger for provider operations
	client              *fasthttp.Client      // HTTP client for API requests
	networkConfig       schemas.NetworkConfig // Network configuration including extra headers
	sendBackRawRequest  bool                  // Whether to include raw request in BifrostResponse
	sendBackRawResponse bool                  // Whether to include raw response in BifrostResponse
}

// NewGoogleCloudTTSProvider creates a new Google Cloud Text-to-Speech provider instance.
func NewGoogleCloudTTSProvider(config *schemas.ProviderConfig, logger schemas.Logger) (*GoogleCloudTTSProvider, error) {
	config.CheckAndSetDefaults()

	requestTimeout := time.Second * time.Duration(config.NetworkConfig.DefaultRequestTimeoutInSeconds)
	client := &fasthttp.Client{
		ReadTimeout:         requestTimeout,
		WriteTimeout:        requestTimeout,
		MaxConnsPerHost:     config.NetworkConfig.MaxConnsPerHost,
		MaxIdleConnDuration: time.Second * time.Duration(config.NetworkConfig.KeepAliveTimeoutInSeconds),
		MaxConnWaitTimeout:  requestTimeout,
		MaxConnDuration:     time.Second * time.Duration(schemas.DefaultMaxConnDurationInSeconds),
		ConnPoolStrategy:    fasthttp.FIFO,
	}

	client = providerUtils.ConfigureProxy(client, config.ProxyConfig, logger)
	client = providerUtils.ConfigureDialer(client, config.NetworkConfig.AllowPrivateNetwork)
	client = providerUtils.ConfigureTLS(client, config.NetworkConfig, logger)

	if config.NetworkConfig.BaseURL == "" {
		config.NetworkConfig.BaseURL = defaultBaseURL
	}
	config.NetworkConfig.BaseURL = strings.TrimRight(config.NetworkConfig.BaseURL, "/")

	return &GoogleCloudTTSProvider{
		logger:              logger,
		client:              client,
		networkConfig:       config.NetworkConfig,
		sendBackRawRequest:  config.SendBackRawRequest,
		sendBackRawResponse: config.SendBackRawResponse,
	}, nil
}

// GetProviderKey returns the provider identifier for Google Cloud Text-to-Speech.
func (provider *GoogleCloudTTSProvider) GetProviderKey() schemas.ModelProvider {
	return schemas.GoogleCloudTTS
}

// supportedSpeechFields are the unified speech fields text:synthesize can take: the voice
// name, the audio encoding, the speaking rate and the voice's language.
var supportedSpeechFields = []string{"voice", "response_format", "speed", "language_code"}

// SupportedUnifiedFields declares the unified fields the provider takes, so core refuses a
// request carrying any other one with caller_unsupported_parameter before a key is chosen.
// The stream variant is declared too: it is refused in SpeechStream, but a request that
// also carries an undeliverable field names that field the same way on both routes.
func (provider *GoogleCloudTTSProvider) SupportedUnifiedFields(requestType schemas.RequestType) ([]string, bool) {
	switch requestType {
	case schemas.SpeechRequest, schemas.SpeechStreamRequest:
		return supportedSpeechFields, true
	}
	return nil, false
}

// Speech performs a text:synthesize request and returns the decoded audio bytes. The
// vendor reports no usage, so the response carries none.
func (provider *GoogleCloudTTSProvider) Speech(ctx *schemas.BifrostContext, key schemas.Key, request *schemas.BifrostSpeechRequest) (*schemas.BifrostSpeechResponse, *schemas.BifrostError) {
	if request == nil || request.Input == nil || request.Input.Input == "" {
		return nil, providerUtils.NewBifrostBadRequestError("speech input text is required")
	}
	if fieldErr := checkSpeechParams(request.Params); fieldErr != nil {
		return nil, fieldErr
	}

	req := fasthttp.AcquireRequest()
	resp := fasthttp.AcquireResponse()
	defer fasthttp.ReleaseRequest(req)
	defer fasthttp.ReleaseResponse(resp)

	providerUtils.SetExtraHeaders(ctx, req, provider.networkConfig.ExtraHeaders, nil)

	req.SetRequestURI(provider.networkConfig.BaseURL + providerUtils.GetPathFromContext(ctx, synthesizePath))
	req.Header.SetMethod(http.MethodPost)
	req.Header.SetContentType("application/json")
	if key.Value.GetValue() != "" {
		req.Header.Set(apiKeyHeader, key.Value.GetValue())
	}

	jsonData, bifrostErr := providerUtils.CheckContextAndGetRequestBody(
		ctx,
		request,
		func() (providerUtils.RequestBodyWithExtraParams, error) {
			return ToGoogleCloudTTSSpeechRequest(request), nil
		})
	if bifrostErr != nil {
		return nil, bifrostErr
	}
	req.SetBody(jsonData)

	latency, bifrostErr, wait := providerUtils.MakeRequestWithContext(ctx, provider.client, req, resp)
	defer wait()
	if bifrostErr != nil {
		return nil, providerUtils.EnrichError(ctx, bifrostErr, jsonData, nil, provider.sendBackRawRequest, provider.sendBackRawResponse, latency)
	}

	ctx.SetValue(schemas.BifrostContextKeyProviderResponseHeaders, providerUtils.ExtractProviderResponseHeaders(resp))

	if resp.StatusCode() != fasthttp.StatusOK {
		return nil, providerUtils.EnrichError(ctx, parseGoogleCloudTTSError(resp), jsonData, nil, provider.sendBackRawRequest, provider.sendBackRawResponse, latency)
	}

	ft, fh := providerUtils.StartPhaseSpan(ctx, "response-finalize")
	body, err := providerUtils.CheckAndDecodeBody(resp)
	if ft != nil {
		if err != nil {
			ft.EndSpan(fh, schemas.SpanStatusError, err.Error())
		} else {
			ft.EndSpan(fh, schemas.SpanStatusOk, "")
		}
	}
	if err != nil {
		return nil, providerUtils.EnrichError(ctx, providerUtils.NewBifrostOperationError(schemas.ErrProviderResponseDecode, err), jsonData, nil, provider.sendBackRawRequest, provider.sendBackRawResponse, latency)
	}

	var synthesizeResp GoogleCloudTTSSynthesizeResponse
	pt, ph := providerUtils.StartResponseParseSpan(ctx)
	umErr := sonic.Unmarshal(body, &synthesizeResp)
	if pt != nil {
		if umErr != nil {
			pt.EndSpan(ph, schemas.SpanStatusError, "response parse failed")
		} else {
			pt.EndSpan(ph, schemas.SpanStatusOk, "")
		}
	}
	if umErr != nil {
		return nil, providerUtils.EnrichError(ctx, providerUtils.NewBifrostOperationError("failed to parse Google Cloud Text-to-Speech response", umErr), jsonData, body, provider.sendBackRawRequest, provider.sendBackRawResponse, latency)
	}
	// A 200 with no audio and no error object is the vendor's failure, not the caller's.
	if synthesizeResp.AudioContent == "" {
		return nil, providerUtils.EnrichError(ctx, schemas.NewProviderEmptyResultError("Google Cloud Text-to-Speech response contained no audio"), jsonData, body, provider.sendBackRawRequest, provider.sendBackRawResponse, latency)
	}

	audioBytes, err := base64.StdEncoding.DecodeString(synthesizeResp.AudioContent)
	if err != nil {
		return nil, providerUtils.EnrichError(ctx, providerUtils.NewBifrostOperationError("failed to decode Google Cloud Text-to-Speech base64 audio", err), jsonData, body, provider.sendBackRawRequest, provider.sendBackRawResponse, latency)
	}

	bifrostResponse := &schemas.BifrostSpeechResponse{
		Audio: audioBytes,
		ExtraFields: schemas.BifrostResponseExtraFields{
			Latency:                 latency.Milliseconds(),
			ProviderResponseHeaders: providerUtils.ExtractProviderResponseHeaders(resp),
		},
	}

	if providerUtils.ShouldSendBackRawRequest(ctx, provider.sendBackRawRequest) {
		providerUtils.ParseAndSetRawRequest(&bifrostResponse.ExtraFields, jsonData)
	}
	if providerUtils.ShouldSendBackRawResponse(ctx, provider.sendBackRawResponse) {
		var rawResponse interface{}
		if err := sonic.Unmarshal(body, &rawResponse); err != nil {
			rawResponse = string(body)
		}
		bifrostResponse.ExtraFields.RawResponse = rawResponse
	}

	return bifrostResponse, nil
}

// SpeechStream is refused: text:synthesize answers with one JSON document, so the
// stream_format field that selects this route cannot be delivered.
