/**
 * The A2A card the fixture agent serves, in the JSON the gateway's card reader
 * accepts (the a2a-go v2 wire shape: wrapped security schemes, a JSON-RPC
 * interface at protocol version 1.0). Generated by serving the same card from
 * a2asrv.NewStaticAgentCardHandler and reading it back through the gateway's
 * own inspection path.
 */
export function fixtureAgentCard(baseUrl: string) {
  return {
    name: "e2e-fixture-agent",
    version: "1",
    description: "Playwright fixture agent",
    capabilities: {},
    defaultInputModes: ["text/plain"],
    defaultOutputModes: ["text/plain"],
    securitySchemes: {
      apiKey: { apiKeySecurityScheme: { location: "header", name: FIXTURE_RUNTIME_HEADER } },
    },
    securityRequirements: [{ schemes: { apiKey: [] } }],
    skills: null,
    supportedInterfaces: [{ protocolBinding: "JSONRPC", protocolVersion: "1.0", url: `${baseUrl}/rpc` }],
  };
}

export interface CardRequest {
  headers: http.IncomingHttpHeaders;
}

/**
 * A loopback HTTP server standing in for an upstream A2A agent. It serves the
 * fixture card and records every request's headers, which is how the tests see
 * which credential the gateway used for a fetch: the one typed into the form,
 * or the masked placeholder a later edit handed back.
 */
export class FixtureAgentServer {
  readonly requests: CardRequest[] = [];
  private server?: http.Server;
  baseUrl = "";

  async start(): Promise<void> {
    this.server = http.createServer((req, res) => {
      if (req.method === "GET" && req.url === FIXTURE_CARD_PATH) {
        this.requests.push({ headers: req.headers });
        res.writeHead(200, { "Content-Type": "application/json" });
        res.end(JSON.stringify(fixtureAgentCard(this.baseUrl)));
        return;
      }
      res.writeHead(404);
      res.end();
    });
    await new Promise<void>((resolve, reject) => {
      this.server!.once("error", reject);
      this.server!.listen(0, "127.0.0.1", () => resolve());
    });
    const { port } = this.server.address() as AddressInfo;
    this.baseUrl = `http://127.0.0.1:${port}`;
  }

  get cardUrl(): string {
    return `${this.baseUrl}${FIXTURE_CARD_PATH}`;
  }

  /** Header values seen on card fetches, oldest first. */
  cardHeaderValues(name: string): (string | undefined)[] {
    return this.requests.map((request) => {
      const value = request.headers[name.toLowerCase()];
      return Array.isArray(value) ? value.join(",") : value;
    });
  }

  async stop(): Promise<void> {
    await new Promise<void>((resolve) => this.server?.close(() => resolve()));
  }
}

/** Agent names must be lowercase slugs; this one is unique per run. */
export function uniqueAgentName(): string {
  return `e2e-agent-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 6)}`;
}
